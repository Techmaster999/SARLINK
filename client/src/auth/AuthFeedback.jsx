import React from 'react';
import { AuthErrorType } from './handleAuthError.js';
import './authFeedback.css';

/**
 * Returns an icon representing the error category
 */
function getFeedbackIcon(type) {
  switch (type) {
    case AuthErrorType.INVALID_CREDENTIALS:
      return (
        <svg className="sarlink-feedback-icon" fill="none" stroke="currentColor" viewBox="0 0 24 24">
          <path strokeLinecap="round" strokeLinejoin="round" strokeWidth="2" d="M12 8v4m0 4h.01M21 12a9 9 0 11-18 0 9 9 0 0118 0z" />
        </svg>
      );
    case AuthErrorType.ACCOUNT_LOCKED:
      return (
        <svg className="sarlink-feedback-icon" fill="none" stroke="currentColor" viewBox="0 0 24 24">
          <path strokeLinecap="round" strokeLinejoin="round" strokeWidth="2" d="M12 15v2m-6 4h12a2 2 0 002-2v-6a2 2 0 00-2-2H6a2 2 0 00-2 2v6a2 2 0 002 2zm10-10V7a4 4 0 00-8 0v4h8z" />
        </svg>
      );
    case AuthErrorType.NETWORK_ERROR:
      return (
        <svg className="sarlink-feedback-icon" fill="none" stroke="currentColor" viewBox="0 0 24 24">
          <path strokeLinecap="round" strokeLinejoin="round" strokeWidth="2" d="M18.364 5.636a9 9 0 010 12.728m0 0l-2.829-2.828m2.829 2.828L3 3m5.636 5.636a5 5 0 017.072 0M6.343 6.343L12 12m0 0v.01" />
        </svg>
      );
    case AuthErrorType.GOOGLE_WORKSPACE_ERROR:
      return (
        <svg className="sarlink-feedback-icon" fill="none" stroke="currentColor" viewBox="0 0 24 24">
          <path strokeLinecap="round" strokeLinejoin="round" strokeWidth="2" d="M9 12l2 2 4-4m5.618-4.016A11.955 11.955 0 0112 2.944a11.955 11.955 0 01-8.618 3.04A12.02 12.02 0 003 9c0 5.591 3.824 10.29 9 11.622 5.176-1.332 9-6.03 9-11.622 0-1.042-.133-2.052-.382-3.016z" />
        </svg>
      );
    default:
      return (
        <svg className="sarlink-feedback-icon" fill="none" stroke="currentColor" viewBox="0 0 24 24">
          <path strokeLinecap="round" strokeLinejoin="round" strokeWidth="2" d="M13 16h-1v-4h-1m1-4h.01M21 12a9 9 0 11-18 0 9 9 0 0118 0z" />
        </svg>
      );
  }
}

/**
 * React Component for displaying user-facing authentication feedback.
 * 
 * Renders clear notifications for:
 * - Invalid credentials
 * - Account lockouts
 * - Network timeouts / drops
 * - Google Workspace identity provider errors
 * 
 * @param {Object} props
 * @param {Object} props.feedback - The feedback object generated by handleAuthError / displayAuthFeedback
 * @param {Function} [props.onDismiss] - Handler to clear feedback
 * @param {Function} [props.onRetry] - Handler to retry authentication action
 */
export function AuthFeedback({ feedback, onDismiss, onRetry }) {
  if (!feedback || !feedback.message) {
    return null;
  }

  const categoryClass = `sarlink-feedback-${feedback.type || AuthErrorType.UNKNOWN_ERROR}`;

  return (
    <div
      className={`sarlink-auth-feedback-container ${categoryClass}`}
      role="alert"
      aria-live="assertive"
    >
      {getFeedbackIcon(feedback.type)}

      <div className="sarlink-feedback-body">
        <div className="sarlink-feedback-title">{feedback.title}</div>
        <div className="sarlink-feedback-message">{feedback.message}</div>

        {feedback.actionableTip && (
          <div className="sarlink-feedback-tip">
            <span>💡 {feedback.actionableTip}</span>
          </div>
        )}

        {feedback.canRetry && onRetry && (
          <div className="sarlink-feedback-actions">
            <button
              type="button"
              className="sarlink-retry-btn"
              onClick={onRetry}
            >
              Retry Sign-In
            </button>
          </div>
        )}
      </div>

      {onDismiss && (
        <button
          type="button"
          className="sarlink-feedback-close-btn"
          aria-label="Dismiss feedback"
          onClick={onDismiss}
        >
          &times;
        </button>
      )}
    </div>
  );
}

export default AuthFeedback;
